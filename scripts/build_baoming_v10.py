def render() -> str:
    module_uses = Counter(
        module
        for _, chapter_units in CHAPTERS
        for unit in chapter_units
        for item in unit.questions
        for module in (*item.leads, *item.points, *item.bonus_points)
    )

    def marked(module: str) -> str:
        label = "共用" if module_uses[module] > 1 else "本题补充"
        return f"**【{label}】** {module}"

    lines = [
        "# 华东师范大学347心理学导论保命手册",
        "",
        "## 前三章·共用补充双加分版V10",
        "",
        "---",
        "",
    ]
    for chapter_title, units in CHAPTERS:
        lines.extend((f"# {chapter_title}", ""))
        for unit in units:
            lines.extend((f"## {unit.title}【{unit.level}】", ""))
            for number, item in enumerate(unit.questions, start=1):
                lines.extend((f"### 押题{number}【{item.kind}】{item.stem}", "", "#### 答案", ""))
                for lead in item.leads:
                    lines.extend((marked(lead), ""))
                for point_number, point in enumerate(item.points, start=1):
                    lines.extend((f"{point_number}. {marked(point)}", ""))
                if item.bonus_points:
                    lines.extend(("**【整体加分】**", ""))
                    first_bonus_number = len(item.points) + 1
                    for point_number, point in enumerate(item.bonus_points, start=first_bonus_number):
                        lines.extend((f"{point_number}. {marked(point)}", ""))
            lines.extend(("---", ""))
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(), encoding="utf-8")


if __name__ == "__main__":
    main()
