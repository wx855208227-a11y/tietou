def replace_guide(text: str) -> str:
    marker = "# 第一章 "
    index = text.index(marker)
    return GUIDE + "\n" + text[index:]


def replace_stars(text: str) -> str:
    for title, stars in STAR_OVERRIDES.items():
        text, count = re.subn(
            rf"^(## [一二三四五六七八九十]+、{re.escape(title)})【[★]+】$",
            rf"\1【{stars}】",
            text,
            flags=re.MULTILINE,
        )
        assert count == 1, (title, count)
    return text


def insert_after(text: str, needle: str, addition: str) -> str:
    assert text.count(needle) == 1, needle
    return text.replace(needle, needle + addition, 1)


