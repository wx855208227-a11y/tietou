def question_ranges(text: str) -> list[tuple[re.Match[str], int]]:
    matches = list(re.finditer(r"^### 押题\d+【(?:简答|论述)】.*$", text, re.MULTILINE))
    ranges: list[tuple[re.Match[str], int]] = []
    for index, match in enumerate(matches):
        end = matches[index + 1].start() if index + 1 < len(matches) else len(text)
        boundary = re.search(r"^#{1,2} ", text[match.end() : end], re.MULTILINE)
        ranges.append((match, match.end() + boundary.start() if boundary else end))
    return ranges


def replace_in_question(text: str, heading_fragment: str, replacements: dict[str, str]) -> str:
    hits = [item for item in question_ranges(text) if heading_fragment in item[0].group(0)]
    assert len(hits) == 1, (heading_fragment, len(hits))
    match, end = hits[0]
    block = text[match.start() : end]
    for old, new in replacements.items():
        assert old in block, (heading_fragment, old)
        block = block.replace(old, new, 1)
    return text[: match.start()] + block + text[end:]


def replace_question_block(text: str, heading_fragment: str, new_block: str) -> str:
    hits = [item for item in question_ranges(text) if heading_fragment in item[0].group(0)]
    assert len(hits) == 1, (heading_fragment, len(hits))
    match, end = hits[0]
    trailing = "\n\n" if text[match.start() : end].endswith("\n\n") else "\n"
    return text[: match.start()] + new_block.strip() + trailing + text[end:]


def promote_to_essay(text: str, question_fragments: tuple[str, ...]) -> str:
    for fragment in question_fragments:
        old = f"### 押题1【简答】{fragment}"
        new = f"### 押题1【论述】{fragment}"
        assert text.count(old) == 1, old
        text = text.replace(old, new, 1)
    return text


