def remove_experimental_design_task(text: str) -> str:
    pattern = re.compile(
        r"\n## 十、综合实验设计【★★★】\n.*?(?=\n## 十一、实验信度【★★★】)",
        re.DOTALL,
    )
    text, count = pattern.subn("\n", text)
    assert count == 1, count
    text = text.replace("## 十一、实验信度【★★★】", "## 十、实验信度【★★★】", 1)
    text = text.replace("## 十二、实验效度【★★★】", "## 十一、实验效度【★★★】", 1)
    return text


