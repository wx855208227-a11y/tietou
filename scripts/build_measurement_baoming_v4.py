QUESTION_RE = re.compile(
    r"(?P<prefix>^### (?P<heading>押题\d+【(?:简答|论述)】.*?)\n\n)"
    r"(?P<body>.*?)"
    r"(?=\n(?:---\n|### 押题|## |# )|\Z)",
    re.MULTILINE | re.DOTALL,
)
TOP_LEVEL_RE = re.compile(r"^(\d+)\.\s")


def transform_body(heading: str, body: str) -> str:
    if heading in CUSTOM_BODY:
        return CUSTOM_BODY[heading]

    paragraphs = [value for value in body.strip().split("\n\n") if value.strip()]
    removals = REMOVE_PARAGRAPHS.get(heading, set())
    paragraphs = [value for value in paragraphs if value not in removals]
    starts = dict(MODULES[heading])
    encountered: set[int] = set()
    current_number = 0
    result: list[str] = []
    for paragraph in paragraphs:
        match = TOP_LEVEL_RE.match(paragraph)
        if match is None:
            result.append(paragraph)
            continue
        original_number = int(match.group(1))
        if original_number in starts:
            result.append(starts[original_number])
            current_number = 0
            encountered.add(original_number)
        current_number += 1
        result.append(TOP_LEVEL_RE.sub(f"{current_number}. ", paragraph, count=1))
    assert encountered == set(starts), (heading, encountered, set(starts))
    return "\n\n".join(result)


def transform(text: str) -> str:
    text = text.replace("## 全本·极简直背版V3", "## 全本·极简直背版V4", 1)
    headings = [match.group("heading") for match in QUESTION_RE.finditer(text)]
    assert len(headings) == len(set(headings)) == 45
    assert set(headings) == set(MODULES), (set(headings) - set(MODULES), set(MODULES) - set(headings))

    def replace(match: re.Match[str]) -> str:
        heading = match.group("heading")
        return match.group("prefix") + transform_body(heading, match.group("body")) + "\n"

    result, count = QUESTION_RE.subn(replace, text)
    assert count == 45
    return result


