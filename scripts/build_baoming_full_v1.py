def first_three() -> str:
    text = V16.read_text(encoding="utf-8")
    start = text.index("# 第一章 ")
    body = text[start:].strip()
    for title, level in LEVELS.items():
        body = re.sub(
            rf"^## {re.escape(title)}【(?:一级|二级)】$",
            f"## {title}【{level}】",
            body,
            flags=re.MULTILINE,
        )
    return body


