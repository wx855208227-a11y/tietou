def unit_name(line: str) -> str:
    return line[3:].split("【", 1)[0].strip()


def normalize_existing_bonus(line: str) -> bool:
    return line.strip().startswith("（加分项：")


def canonicalize_definition(line: str) -> str:
    match = TAG_RE.search(line)
    if not match:
        return line
    term = match.group(1)
    if term not in CANONICAL_DEFINITIONS:
        raise KeyError(f"缺少统一定义：{term}")
    prefix_match = PREFIX_RE.match(line.strip())
    prefix = prefix_match.group(1) if prefix_match else ""
    return f"{prefix}{CANONICAL_DEFINITIONS[term]} **【名词解释：{term}】**"


def apply_body_replacements(line: str) -> str:
    result = line
    for old, new in BODY_REPLACEMENTS.items():
        result = result.replace(old, new)
    return result


def append_bonus(line: str, content: str) -> str:
    return f"{line.rstrip()} **【加分项：{content}】**"


def transform_unit(name: str, lines: list[str]) -> list[str]:
    cleaned = [line for line in lines if not normalize_existing_bonus(line)]
    transformed = [apply_body_replacements(canonicalize_definition(line)) for line in cleaned]

    if name == "一、心理学的含义与研究对象":
        for index, line in enumerate(transformed):
            if "【名词解释：心理学】" in line:
                transformed.insert(index + 1, "心理学的研究对象主要包括**心理过程**和**人格**。")
                break

    placements = BONUS_PLACEMENTS.get(name, ())
    for needle, content in placements:
        indexes = [i for i, line in enumerate(transformed) if needle in line]
        if len(indexes) != 1:
            raise ValueError(f"{name} 的加分项定位不唯一：{needle} -> {len(indexes)}")
        index = indexes[0]
        transformed[index] = append_bonus(transformed[index], content)
    return transformed


def transform_markdown(source: str) -> str:
    lines = source.splitlines()
    output: list[str] = []
    index = 0
    while index < len(lines):
        line = lines[index]
        if line == "## 前三章·直背综合答案版":
            output.append("## 前三章·直背综合答案版V2")
            index += 1
            continue
        if line.startswith("## "):
            name = unit_name(line)
            block = [line]
            index += 1
            while index < len(lines) and not lines[index].startswith("## ") and not lines[index].startswith("# "):
                block.append(lines[index])
                index += 1
            output.extend([block[0], *transform_unit(name, block[1:])])
            continue
        output.append(line)
        index += 1

    transformed = "\n".join(output).rstrip() + "\n"
    validate(transformed)
    return transformed


def normalized_definition(line: str) -> str:
    line = PREFIX_RE.sub("", line.strip(), count=1)
    line = TAG_RE.sub("", line).strip()
    line = BONUS_TAG_RE.sub("", line).strip()
    return line


def validate(markdown: str) -> None:
    occurrences: dict[str, list[str]] = defaultdict(list)
    for line in markdown.splitlines():
        match = TAG_RE.search(line)
        if match:
            occurrences[match.group(1)].append(normalized_definition(line))
    missing = set(CANONICAL_DEFINITIONS) - set(occurrences)
    if missing:
        raise ValueError(f"统一定义未被调用：{sorted(missing)}")
    inconsistent = {
        term: values for term, values in occurrences.items() if len(set(values)) > 1
    }
    if inconsistent:
        raise ValueError(f"重复定义不一致：{inconsistent}")
    if re.search(r"^（加分项：", markdown, re.MULTILINE):
        raise ValueError("仍存在答案末尾独立加分项")
    expected_bonus = sum(len(items) for items in BONUS_PLACEMENTS.values())
    actual_bonus = markdown.count("【加分项：")
    if actual_bonus != expected_bonus:
        raise ValueError(f"加分项数量异常：{actual_bonus} != {expected_bonus}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    arguments = parser.parse_args()
    source = arguments.input.read_text(encoding="utf-8")
    transformed = transform_markdown(source)
    arguments.output.parent.mkdir(parents=True, exist_ok=True)
    arguments.output.write_text(transformed, encoding="utf-8")


if __name__ == "__main__":
    main()
