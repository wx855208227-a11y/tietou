BANNED_META_LABELS = (
    "**判断方法**",
    "**案例判断**",
    "**判断原则**",
    "**辨析步骤**",
    "**调控步骤**",
)


def transform(source: str) -> str:
    output = source
    for old, new, expected_count in REPLACEMENTS:
        actual_count = output.count(old)
        if actual_count != expected_count:
            raise ValueError(
                f"替换定位数量异常：{old[:36]} -> {actual_count} != {expected_count}"
            )
        output = output.replace(old, new)
    output = output.replace("++", "")
    if "++" in output:
        raise ValueError("仍存在关键句下划线标记")
    remaining_meta = [label for label in BANNED_META_LABELS if label in output]
    if remaining_meta:
        raise ValueError(f"仍存在答题思路式标签：{remaining_meta}")
    validate(output)
    return output


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    arguments = parser.parse_args()
    source = arguments.input.read_text(encoding="utf-8")
    transformed = transform(source)
    arguments.output.parent.mkdir(parents=True, exist_ok=True)
    arguments.output.write_text(transformed, encoding="utf-8")


if __name__ == "__main__":
    main()
