def source_units(text: str) -> dict[str, str]:
    matches = list(re.finditer(r"^## (.+?)【(?:★★★|★★|★)】\n", text, re.MULTILINE))
    units: dict[str, str] = {}
    for index, match in enumerate(matches):
        end = matches[index + 1].start() if index + 1 < len(matches) else len(text)
        block = text[match.start() : end]
        block = re.split(r"^# ", block, maxsplit=1, flags=re.MULTILINE)[0].strip()
        name = re.sub(r"^[一二三四五六七八九十]+、", "", match.group(1))
        units[name] = block
    return units


def retitle(block: str, ordinal: str, name: str, level: str | None = None) -> str:
    match = re.match(r"^## .+?【(★★★|★★|★)】", block)
    assert match, block[:120]
    chosen = level or match.group(1)
    return re.sub(
        r"^## .+?【(?:★★★|★★|★)】",
        f"## {ordinal}、{name}【{chosen}】",
        block,
        count=1,
    ).strip()


