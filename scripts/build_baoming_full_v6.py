def existing_expansions(text: str) -> dict[str, str]:
    values: dict[str, list[str]] = defaultdict(list)
    for name, expansion in PAIR_RE.findall(text):
        if expansion not in values[name]:
            values[name].append(expansion)
    result = {name: expansions[0] for name, expansions in values.items()}
    result.update(OVERRIDES)
    return result


def transform(text: str) -> tuple[str, dict[str, str]]:
    names = set(re.findall(r"【名词解释：([^】]+)】", text))
    names.discard("……")
    expansions = existing_expansions(text)
    assert not (set(NEW_EXPANSIONS) & set(expansions) - set(OVERRIDES)), sorted(
        set(NEW_EXPANSIONS) & set(expansions) - set(OVERRIDES)
    )
    expansions.update(NEW_EXPANSIONS)
    expansions.update(OVERRIDES)
    assert names == set(expansions), (
        sorted(names - expansions.keys()),
        sorted(expansions.keys() - names),
    )

    def replacement(match: re.Match[str]) -> str:
        name = match.group(1)
        if name == "……":
            return match.group(0)
        return f"【名词解释：{name}】【扩容（选用）：{expansions[name]}】"

    result = TAG_RE.sub(replacement, text)
    result = result.replace("## 全本·采分关键词精校版V5", "## 全本·名解完整扩容版V6", 1)
    result = result.replace(
        "> 每道押题均配置一份可直接背写的独立答案，按“总起—分点—总结”组织。括号外是必须优先掌握的基础采分点；`【名词解释：……】`标在完整定义句末；`【扩容（选用）：……】`紧跟所扩充的采分点，可按题目分值和时间选写。",
        "> 每道押题均配置一份可直接背写的独立答案，按“总起—分点—总结”组织。括号外是必须优先掌握的基础采分点；每个`【名词解释：……】`后均紧跟一条标准`【扩容（选用）：……】`，二者共同构成正常名解容量；其他扩容也紧跟所扩充的采分点，可按题目分值和时间选写。",
        1,
    )
    return result, expansions


