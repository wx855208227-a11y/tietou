def units(path: Path):
    chapter = ""
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("# ") and not line.startswith("## "):
            chapter = line[2:].strip()
        match = re.match(r"^## [一二三四五六七八九十]+、(.+?)【([★]+)】$", line)
        if match:
            yield chapter, match.group(1), match.group(2)


