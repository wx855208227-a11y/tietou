def main() -> None:
    outputs = {
        "普通心理学": (GENERAL_OUTPUT, GENERAL_SOURCE.read_text(encoding="utf-8")),
        "实验心理学": (EXPERIMENT_OUTPUT, build_experiment()),
        "心理与教育测量": (MEASUREMENT_OUTPUT, MEASUREMENT_SOURCE.read_text(encoding="utf-8")),
    }
    stats: dict[str, dict[str, object]] = {}
    for subject, (path, text) in outputs.items():
        stats[subject] = validate(subject, text)
        path.write_text(text, encoding="utf-8")
        print(path)
    write_ledger()
    write_report(stats)
    print(LEDGER)
    print(SCOPE_REPORT)


if __name__ == "__main__":
    main()
