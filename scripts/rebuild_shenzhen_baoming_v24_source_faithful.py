EXPECTED_CHAPTERS = v23.EXPECTED_CHAPTERS
EXPECTED_COUNTS = {
    "普通心理学": (15, 75, 90),
    "实验心理学": (9, 40, 41),
    "心理与教育测量": (13, 41, 46),
}


def build_experiment() -> str:
    text = EXPERIMENT_SOURCE.read_text(encoding="utf-8")
    cut = text.index("# 第六章 注意")
    return text[:cut].rstrip() + "\n\n" + LATER_CHAPTERS.strip() + "\n"


def chapters(text: str) -> tuple[str, ...]:
    return tuple(
        match.group(1).strip()
        for match in re.finditer(r"^# ((?:第[^\n]+章|补充章)[^\n]*)$", text, re.MULTILINE)
    )


def units(text: str) -> list[tuple[str, str]]:
    return [
        (match.group(1).strip(), match.group(2))
        for match in re.finditer(
            r"^## ([一二三四五六七八九十百]+、[^\n【]+)【(★{1,3})】$",
            text,
            re.MULTILINE,
        )
    ]


def question_count(text: str) -> int:
    return len(re.findall(r"^### 押题\d+【(?:简答|论述)】", text, re.MULTILINE))


def validate(subject: str, text: str) -> dict[str, object]:
    found_chapters = chapters(text)
    found_units = units(text)
    found_questions = question_count(text)
    assert found_chapters == EXPECTED_CHAPTERS[subject], (subject, found_chapters)
    assert (len(found_chapters), len(found_units), found_questions) == EXPECTED_COUNTS[subject]
    assert "速背手册或一本通" not in text
    if subject == "实验心理学":
        one_star = {title for title, star in found_units if star == "★"}
        assert one_star == {
            "二、实验心理学的科学属性与实证研究",
            "一、直接知觉论",
            "四、内隐学习",
            "一、思维的研究方法",
            "二、情绪的认知研究",
            "三、情绪的测量",
        }
        assert "间接知觉论" not in text[text.index("# 第六章 注意") :]
        assert "多阶段选择模型" not in text
        assert "加工分离程序" not in text
        assert "皮肤电" not in text[text.index("# 第六章 注意") :]
        assert "请设计" not in text and "设计一项实验" not in text
    return {
        "chapters": len(found_chapters),
        "units": len(found_units),
        "questions": found_questions,
        "stars": Counter(star for _title, star in found_units),
    }


def write_ledger() -> None:
    with LEDGER.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle, delimiter="\t")
        writer.writerow(("速背章节", "速背采分点", "V24去向", "V24考点", "关键词继承"))
        writer.writerows(POINTS)


