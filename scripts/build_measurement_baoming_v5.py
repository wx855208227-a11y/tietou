def add_reliability_comparison(body: str) -> str:
    # 最终的横向比较模块已经集中说明一致性来源和误差来源，因此删除
    # 各方法下与之完全重复的过渡句；标准扩容仍保留适用前提和计算提示。
    redundant_paragraphs = (
        "\n\n它反映测验**跨时间的一致性**。",
        "\n\n（2）**适用前提**：**所测特性必须稳定**；**被试的记忆和练习效果相同**；两次测试期间的学习效果无差别。（两次测量间隔过短容易**产生记忆和练习效应**，间隔过长又可能发生真实变化。）",
        "\n\n它反映测验**跨形式的一致性**。",
        "\n\n（1）**计算方法**：**对同一组被试先实施复份A**，再在最短时距内实施复份B，计算两次测验分数的相关。",
        "\n\n**两个评分者可用积差相关或等级相关**，**三个以上评分者可用肯德尔和谐系数**。",
    )
    for paragraph in redundant_paragraphs:
        assert body.count(paragraph) == 1, paragraph
        body = body.replace(paragraph, "", 1)
    marker = "\n\n综上，重测、复本、稳定—等值、内在一致性和评分者信度分别考察跨时间、跨形式、跨时间与形式、跨项目和跨评分者的一致性，应根据测验用途和主要误差来源选择。"
    assert marker in body
    comparison = """

各种信度估计方法的**联系**在于：它们都通过比较同一测量对象在不同时间、形式、项目组合或评分者条件下的结果，估计测量的一致性和随机误差。

各种信度估计方法的**主要区别**如下：

1. **一致性来源不同**：重测信度考察跨时间一致性，复本信度考察跨形式一致性，稳定—等值系数同时考察跨时间与形式一致性，内在一致性信度考察跨项目一致性，评分者信度考察跨评分者一致性。

2. **主要误差来源不同**：重测信度主要受时间、成熟和练习影响；复本信度主要受题目取样与复本等值性影响；稳定—等值系数同时受两类误差影响；内在一致性信度主要受项目同质性影响；评分者信度主要受评分标准和评分者差异影响。
"""
    return body.replace(marker, comparison + marker, 1)


