def transform_body(heading: str, body: str) -> str:
    if heading in CUSTOM_BODIES:
        body = CUSTOM_BODIES[heading]
    elif heading == "押题1【论述】论述信度的**主要估计方法**，并比较其所反映的一致性及误差来源。":
        body = add_reliability_comparison(body)
    elif heading == "押题2【简答】简述常模的**相对性**，并比较常模与标准。":
        body = add_norm_standard_contact(body)
    return TERM_RE.sub(
        lambda match: match.group(0) if match.group("term") in ADMITTED_TERMS else "",
        body,
    )


def transform(text: str) -> str:
    # 保留“极简直背版”前缀以复用已经验收的黑白打印、圆括号扩容、
    # 正文字号统一和纯标题封面渲染逻辑；任务驱动是内容版本特征。
    text = text.replace("## 全本·极简直背版V4", "## 全本·极简直背版V5", 1)
    source_headings = [match.group("heading") for match in QUESTION_RE.finditer(text)]
    assert len(source_headings) == len(set(source_headings)) == 45

    def replace(match: re.Match[str]) -> str:
        old_heading = match.group("heading")
        new_heading = HEADING_REPLACEMENTS.get(old_heading, old_heading)
        body = transform_body(old_heading, match.group("body"))
        return f"### {new_heading}\n\n{body.strip()}\n"

    result, count = QUESTION_RE.subn(replace, text)
    assert count == 45
    final_headings = [match.group("heading") for match in QUESTION_RE.finditer(result)]
    assert len(final_headings) == len(set(final_headings)) == 45
    actual_terms = set(TERM_RE.findall(result))
    assert actual_terms == ADMITTED_TERMS, (ADMITTED_TERMS - actual_terms, actual_terms - ADMITTED_TERMS)
    return result


