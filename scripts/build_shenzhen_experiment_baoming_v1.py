    parts = ["# 深圳大学347实验心理学保命手册", "", GUIDE.rstrip()]
    for chapter, names in CHAPTER_PLAN.items():
        parts.extend(("", f"# {chapter}", ""))
        for index, name in enumerate(names):
            ordinal = NUMERALS[index]
            if name.startswith("@"):
                block = ADDITIONAL[name[1:]].strip()
                block = re.sub(
                    r"^## .+?【(★★★|★★|★)】",
                    lambda match: f"## {ordinal}、{name[1:]}【{match.group(1)}】",
                    block,
                    count=1,
                )
