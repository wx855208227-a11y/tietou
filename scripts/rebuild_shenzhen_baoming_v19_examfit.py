def apply_title_revisions(subject: str, text: str) -> str:
    for old, new in TITLE_REVISIONS[subject]:
        count = text.count(old)
        assert count == 1, (subject, old, count)
        text = text.replace(old, new, 1)
    return text


def build_subject(subject: str) -> str:
    text = INPUTS[subject].read_text(encoding="utf-8")
    if subject == "普通心理学":
        text = replace_question(text, "论述问题解决的含义", PROBLEM_SOLVING)
    return apply_title_revisions(subject, text).rstrip() + "\n"


def main() -> None:
    for subject, output in OUTPUTS.items():
        content = build_subject(subject)
        output.write_text(content, encoding="utf-8")
        print(output)


if __name__ == "__main__":
    main()
