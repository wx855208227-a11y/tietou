def transform_question(question, key: tuple[int, int, int]) -> Question:
    source = QUESTION_LINE_OVERRIDES.get(key, question.lines)
    source_lines: list[AnswerLine] = []
    for line in source:
        text = line.text
        line_expansions = tuple(
            EXPANSION_REWRITES.get(clean_expansion(item), clean_expansion(item))
            for item in line.expansions
        )
        match = INLINE_EXAMPLE_RE.search(text)
        if match:
            text = text[: match.start()]
            line_expansions += (f"例如，{match.group(1)}",)
        related_match = RELATED_QUESTION_RE.search(text)
        if related_match:
            text = text[: related_match.start()]
            line_expansions += (f"相关问题如{related_match.group(1)}",)
        source_lines.append(AnswerLine(line.level, text, line_expansions))

    # 空正文扩容必须回到真正的上位点，不能误跟最后一个下位点。
    rebuilt: list[AnswerLine] = []
    for line in source_lines:
        if line.text:
            rebuilt.append(line)
            continue
        assert line.expansions
        if key == (0, 0, 1):
            target = max(index for index, item in enumerate(rebuilt) if item.level == 1)
            target = 0  # “三种过程的关系”扩充第一大点“心理过程的构成”。
        else:
            target = len(rebuilt) - 1
        rebuilt[target] = replace(
            rebuilt[target],
            expansions=rebuilt[target].expansions + tuple(line.expansions),
        )

    if key in PROMOTE_FIRST_LINE:
        rebuilt[0] = replace(rebuilt[0], level=0)
    elif key in INTRODUCTIONS:
        rebuilt.insert(0, AnswerLine(0, INTRODUCTIONS[key]))

    bound_final_indexes: set[int] = set()
    for final_index, target_keyword in enumerate(FINAL_EXPANSION_BINDINGS.get(key, ())):
        matches = [
            index
            for index, item in enumerate(rebuilt)
            if first_keyword(item.text) == target_keyword
        ]
        if not matches:
            raise AssertionError(f"找不到整体扩容的绑定点：{key} -> {target_keyword}")
        target_index = matches[-1]
        rebuilt[target_index] = replace(
            rebuilt[target_index],
            expansions=rebuilt[target_index].expansions
            + (clean_expansion(question.final_expansions[final_index]),),
        )
        bound_final_indexes.add(final_index)

    enriched: list[AnswerLine] = []
    keyword_occurrences: dict[str, int] = {}
    for line in rebuilt:
        keyword = first_keyword(line.text)
        keyword_occurrences[keyword] = keyword_occurrences.get(keyword, 0) + 1
        if line.expansions or not line.text:
            enriched.append(line)
            continue
        occurrence = keyword_occurrences[keyword]
        optional = QUESTION_OCCURRENCE_EXPANSIONS.get((*key, keyword, occurrence))
        optional = optional or QUESTION_EXPANSIONS.get((*key, keyword))
        if line.level > 0:
            optional = optional or EXPANSIONS_BY_KEYWORD.get(keyword)
        if optional and clean_expansion(optional) not in clean_expansion(line.text):
            line = replace(line, expansions=(clean_expansion(optional),))
        enriched.append(line)

    enriched.extend(ESSAY_EXTRA_LINES.get(key, ()))
    conclusion = CONCLUSIONS[key]
    enriched.append(AnswerLine(0, conclusion))

    final_expansions = () if key in SUPPRESS_FINAL_EXPANSIONS else tuple(
        clean_expansion(item)
        for index, item in enumerate(question.final_expansions)
        if index not in bound_final_indexes
        and not plain(item).startswith(("综上", "总体而言"))
    )
    return Question(question.kind, question.stem, tuple(enriched), final_expansions)


def build_chapters() -> tuple[tuple[str, tuple[Unit, ...]], ...]:
    chapters: list[tuple[str, tuple[Unit, ...]]] = []
    for chapter_index, (chapter_title, units) in enumerate(BASE.CHAPTERS):
        rebuilt_units: list[Unit] = []
        for unit_index, unit in enumerate(units):
            questions = tuple(
                transform_question(question, (chapter_index, unit_index, question_index))
                for question_index, question in enumerate(unit.questions)
            )
            rebuilt_units.append(Unit(unit.title, unit.level, questions))
        chapters.append((chapter_title, tuple(rebuilt_units)))
    return tuple(chapters)


CHAPTERS = build_chapters()


def append_line(lines: list[str], line: AnswerLine, first_number: int, second_number: int) -> None:
    if line.level == 0:
        prefix = ""
    elif line.level == 1:
        prefix = f"{first_number}. "
    elif line.level == 2:
        prefix = f"（{second_number}）"
    else:
        raise ValueError(f"不支持的答案层级：{line.level}")
    content = f"{prefix}{line.text}"
    if line.expansions:
        content += "".join(expansion(item) for item in line.expansions)
    lines.extend((content, ""))


def render() -> str:
    lines = [
        "# 华东师范大学347心理学导论保命手册",
        "",
        "## 前三章·总分总同行扩容版V15",
        "",
        "> 每道押题均按“总起—分点—总结”组织；一级编号是主要采分角度，二级编号是其下位内容；单点`【扩容（选用）：……】`紧跟对应采分句，按题目分值和时间选写。",
        "",
        "---",
        "",
    ]
    for chapter_title, units in CHAPTERS:
        lines.extend((f"# {chapter_title}", ""))
        for unit in units:
            lines.extend((f"## {unit.title}【{unit.level}】", ""))
            for number, item in enumerate(unit.questions, start=1):
                lines.extend((f"### 押题{number}【{item.kind}】{item.stem}", ""))
                first_number = 0
                second_number = 0
                for line in item.lines:
                    if line.level == 1:
                        first_number += 1
                        second_number = 0
                    elif line.level == 2:
                        if first_number == 0:
                            raise AssertionError(f"二级采分点缺少上位一级采分点：{item.stem}")
                        second_number += 1
                    append_line(lines, line, first_number, second_number)
                for optional_text in item.final_expansions:
                    lines.extend((expansion(optional_text), ""))
            lines.extend(("---", ""))
    return "\n".join(lines).rstrip() + "\n"


