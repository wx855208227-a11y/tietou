def transform(text: str) -> str:
    names = set(TAG_RE.findall(text))
    assert names == set(EXPANSIONS), (sorted(names - EXPANSIONS.keys()), sorted(EXPANSIONS.keys() - names))

    def replacement(match: re.Match[str]) -> str:
        name = match.group(1)
        return f"【名词解释：{name}】【扩容（选用）：{EXPANSIONS[name]}】"

    result = TAG_RE.sub(replacement, text)
    result = result.replace("## 全本·逐题直背版V1", "## 全本·名解完整扩容版V2")
    return result


def main() -> None:
    source = SOURCE.read_text(encoding="utf-8")
    result = transform(source)
    OUTPUT.write_text(result, encoding="utf-8")
    print(OUTPUT)


if __name__ == "__main__":
    main()
