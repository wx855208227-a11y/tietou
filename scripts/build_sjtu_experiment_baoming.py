def renumber_questions(text: str) -> str:
    blocks = re.split(r"(?=^## )", text, flags=re.MULTILINE)
    output: list[str] = []
    for block in blocks:
        number = 0
        def repl(match: re.Match[str]) -> str:
            nonlocal number
            number += 1
            return f"### 押题{number}【{match.group(1)}】"
        output.append(re.sub(r"^### 押题\d+【(简答|论述)】", repl, block, flags=re.MULTILINE))
    return "".join(output)


