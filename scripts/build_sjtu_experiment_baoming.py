def cut_unsupported_tail(text: str) -> str:
    # These independent units came from the ECNU edition; they are not retained as SJTU prediction units.
    index = text.index("\n# 常见的心理学实验")
    return text[:index].rstrip() + "\n"


def insert_after(text: str, needle: str, addition: str) -> str:
    assert text.count(needle) == 1, needle
    return text.replace(needle, needle + addition, 1)


