def apply_decision(answer: str, decision: Decision, key: tuple[str, int]) -> str:
    output = answer
    for old, new in decision.replacements:
        count = output.count(old)
        assert count == 1, (key, "replacement count", count, old)
        output = output.replace(old, new, 1)
    for term in decision.bold_terms:
        parts = output.split("**")
        count = 0
        for index in range(0, len(parts), 2):
            occurrences = parts[index].count(term)
            if occurrences:
                parts[index] = parts[index].replace(term, f"**{term}**")
                count += occurrences
        assert count >= 1, (key, "unmarked bold term not found", term)
        output = "**".join(parts)
    return output


def build(allow_incomplete: bool) -> None:
    reviewed = set(DECISIONS)
    expected = {
        (subject, index)
        for subject, (_, _, question_count) in SUBJECTS.items()
        for index in range(1, question_count + 1)
    }
    if not allow_incomplete:
        assert reviewed == expected, ("unreviewed questions", sorted(expected - reviewed))

    ledger_rows: list[dict[str, str]] = []
    for subject, (source_path, output_path, question_count) in SUBJECTS.items():
        text = source_path.read_text(encoding="utf-8")
        for question_index in range(1, question_count + 1):
            key = (subject, question_index)
            if key not in DECISIONS:
                continue
            questions = split_questions(text)
            chapter, title, answer = questions[question_index - 1]
            decision = DECISIONS[key]
            revised = apply_decision(answer, decision, key)
            assert text.count(answer) == 1, (key, "answer boundary not unique")
            text = text.replace(answer, revised, 1)
            ledger_rows.append(
                {
                    "科目": subject,
                    "题号": str(question_index),
                    "章节": chapter,
                    "题目": title,
                    "速背继承补正": "；".join(decision.inherited) or "无",
                    "补充关键词": "；".join(decision.supplemental) or "无",
                    "删除或缩界": "；".join(decision.removed) or "无",
                    "修改项数": str(len(decision.replacements) + len(decision.bold_terms)),
                    "逐题复核": "通过",
                    "说明": decision.note,
                }
            )
        output_path.write_text(text, encoding="utf-8")

    LEDGER.parent.mkdir(parents=True, exist_ok=True)
    with LEDGER.open("w", encoding="utf-8", newline="") as file:
        writer = csv.DictWriter(file, fieldnames=list(ledger_rows[0]), delimiter="\t")
        writer.writeheader()
        writer.writerows(ledger_rows)
    print(f"reviewed={len(reviewed)}/{len(expected)} ledger_rows={len(ledger_rows)}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--allow-incomplete", action="store_true")
    arguments = parser.parse_args()
    build(arguments.allow_incomplete)


if __name__ == "__main__":
    main()
