def _align_shared_formulae(text: str) -> str:
    return (
        text.replace("**S=KlgI**", "**P=KlgI**")
        .replace("**ΔI/I=K**", "**K=ΔI/I**")
        .replace("**内在一致性信度**", "**同质性信度**")
        .replace("【名词解释：内在一致性信度】", "【名词解释：同质性信度】")
    )


def build_general() -> str:
    text = build_general_v5()
    text = replace_question(text, "论述**韦伯定律、费希纳定律和斯蒂文斯幂定律**", PSYCHOPHYSICAL_LAWS)
    text = replace_question(text, "比较颜色视觉的**三色理论、对立过程理论和两阶段理论**", COLOR_VISION)
