def main() -> None:
    validate_content()
    text = OUTPUT.read_text(encoding="utf-8")
    speed_text = docx_text(SPEED)
    yibentong_text = docx_text(YIBENTONG)
    combined = speed_text + yibentong_text
    units = re.findall(r"^## (.+)【(★★★|★★|★)】$", text, re.MULTILINE)
    assert len(SOURCE_META) == 49
    assert {title for title, _ in units} == set(SOURCE_META)

    rows: list[str] = []
    for index, (title, star) in enumerate(units, start=1):
        level, anchors = SOURCE_META[title]
        missing = [anchor for anchor in anchors if anchor not in combined]
        assert not missing, (title, missing)
        if level == "一级":
            assert star in {"★★★", "★★"}, (title, level, star)
        else:
            assert star == "★", (title, level, star)
        speed_hits = [anchor for anchor in anchors if anchor in speed_text]
        yibentong_hits = [anchor for anchor in anchors if anchor in yibentong_text]
        assert speed_hits, title
        rows.append(
            f"| {index} | {title} | 速背原{level} | {star} | "
            f"{'、'.join(speed_hits)} | {'、'.join(yibentong_hits) or '—'} |"
        )

    names = sorted(set(TAG_RE.findall(text)))
    assert len(names) == 69
    missing_names = [name for name in names if name not in combined]
    assert not missing_names, missing_names
    assert EVIDENCE.is_file() and "逐题证据" in EVIDENCE.read_text(encoding="utf-8")

    inputs = {
        "实验速背手册": SPEED,
        "实验一本通": YIBENTONG,
        "华东真题册": TARGET_QUESTIONS,
        "华东考纲": OUTLINE,
        "312题库": PUBLIC_312,
        "其他347题库": PUBLIC_347,
    }
    report = (
        "# 华东实验心理学保命手册V1来源审计报告\n\n"
        "## 审计结论\n\n"
        "- 49个单元均能在实验速背手册或实验一本通中定位；69个名词解释名称均在双源范围内。\n"
        "- 三星、二星只对应速背原一级；一星只对应速背原二级。华东真题决定命题侧重，其他347和312真题只验证可考性，不写入范围外知识。\n"
        "- 答案主体以速背手册表述为主，一本通只用于同一知识点的必要补齐、定义扩容和实验步骤校准。\n\n"
        "## 输入文件哈希\n\n"
        + "\n".join(f"- {name}：`{digest(path)}`" for name, path in inputs.items())
        + "\n\n## 单元定位与星级映射\n\n"
        "| 序号 | 单元 | 速背级别 | 成品星级 | 速背定位词 | 一本通复核词 |\n"
        "|---:|---|---|---|---|---|\n"
        + "\n".join(rows)
        + "\n"
    )
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(report, encoding="utf-8")
    print(f"实验心理学保命手册V1来源审计通过：49单元、69个名解全部落在速背／一本通边界内；报告={REPORT}")


if __name__ == "__main__":
    main()
