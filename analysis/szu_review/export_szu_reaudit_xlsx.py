def page_key(item: dict[str, object]) -> tuple[int, str, str]:
    value = item["一本通实际页码"]
    if isinstance(value, int):
        number = value
    else:
        text = str(value)
        digits = "".join(ch if ch.isdigit() else " " for ch in text).split()
        number = int(digits[0]) if digits else 9999
    return number, str(item["章节"]), str(item["具体位置"])


