def add_risk_sheet(wb: Workbook) -> None:
    ws = wb.create_sheet("待确认_教材或补充来源风险")
    ws.append(HEADERS)
    selected = [
        item for item in ISSUES
        if item["置信度"] != "高"
        or "待确认" in str(item["来源性质"])
        or "专业判断" in str(item["来源性质"])
        or "教材原文风险" in str(item["来源性质"])
    ]
    for number, item in enumerate(selected, 1):
        ws.append([number] + [item[header] for header in HEADERS[1:]])
    style_table(ws, [8, 30, 11, 20, 18, 30, 48, 12, 62, 58, 10, 29, 12, 24])
    ws.auto_filter.ref = f"A1:N{ws.max_row}"


def add_second_review_sheet(wb: Workbook) -> None:
    ws = wb.create_sheet("强二级复核")
    ws.append(HEADERS)
    selected = [item for item in ISSUES if item["严重程度"] == "高" or item["置信度"] != "高"]
    for number, item in enumerate(selected, 1):
        ws.append([number] + [item[header] for header in HEADERS[1:]])
    style_table(ws, [8, 30, 11, 20, 18, 30, 48, 12, 62, 58, 10, 29, 12, 24])
    ws.auto_filter.ref = f"A1:N{ws.max_row}"
    for row in ws.iter_rows(min_row=2):
        fill = HIGH if row[2].value == "高" else GRAY
        for cell in row:
            cell.fill = PatternFill("solid", fgColor=fill)


def validate_workbook(path: Path) -> None:
    with ZipFile(path) as archive:
        assert archive.testzip() is None
        assert "xl/workbook.xml" in archive.namelist()
    wb = load_workbook(path, data_only=False)
    assert wb.sheetnames == ["问题总表", "章节覆盖证据", "审核说明", "待确认_教材或补充来源风险", "强二级复核"]
    ws = wb["问题总表"]
    assert ws.max_row == len(ISSUES) + 1
    assert [ws.cell(row, 1).value for row in range(2, ws.max_row + 1)] == list(range(1, len(ISSUES) + 1))
    for row in range(2, ws.max_row + 1):
        assert ws.cell(row, 5).value not in (None, "")
        assert ws.cell(row, 9).value not in (None, "")
        assert ws.cell(row, 10).value not in (None, "")
    assert ws.auto_filter.ref == f"A1:N{ws.max_row}"
    assert ws.freeze_panes == "A2"
    coverage = wb["章节覆盖证据"]
    assert coverage.max_row == len(CHAPTERS) + 2
    assert all(coverage.cell(row, 3).value for row in range(2, coverage.max_row + 1))


