def validate_workbook(path: Path) -> None:
    wb = load_workbook(path, data_only=False)
    assert wb.sheetnames == ["问题总表", "章节覆盖", "审核说明", "待确认_教材风险", "强二级复核"]
    ws = wb["问题总表"]
    assert ws.max_row == len(ISSUES) + 1
    numbers = [ws.cell(i, 1).value for i in range(2, ws.max_row + 1)]
    assert numbers == list(range(1, len(ISSUES) + 1))
    assert all(ws.cell(i, 5).value not in (None, "") for i in range(2, ws.max_row + 1))
    assert all(ws.cell(i, 10).value not in (None, "") for i in range(2, ws.max_row + 1))
    assert ws.auto_filter.ref == f"A1:N{ws.max_row}"
    assert ws.freeze_panes == "A2"


